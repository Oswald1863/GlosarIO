const indexRoot = document.querySelector("#index-grid");
const normalizeText = (value) => value.normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLocaleLowerCase("es");
let conceptNumber = 1;
conceptBlocks.forEach((block) => {
  block.entries = block.topics.flatMap((topic) =>
    topic.subtopics.flatMap((subtopic) =>
      subtopic.concepts.map((concept) => {
        const name = typeof concept === "string" ? concept : concept.name;
        const number = conceptNumber++;
        const url = typeof concept === "string"
          ? (conceptLinks[number] || "")
          : (concept.url || conceptLinks[number] || "");
        return { number, name, url, topic: topic.title, subtopic: subtopic.title };
      })
    )
  );
});

if (indexRoot) {
  indexRoot.innerHTML = conceptBlocks.map((block) => `
    <section class="index-card" aria-labelledby="index-block-${block.number}">
      <div class="index-card-heading">
        <div>
          <span class="index-block-label">BLOQUE ${String(block.number).padStart(2, "0")}</span>
          <h3 id="index-block-${block.number}">Conceptos ${block.range}</h3>
        </div>
        <span class="index-total" data-index-total data-total="${block.entries.length}">${block.entries.length}</span>
      </div>
      <ol class="index-list">
        ${block.entries.map((entry) => `
          <li data-concept-name="${normalizeText(entry.name)}">
            <a class="index-link" href="${entry.url || `#bloque-${block.number}`}"${entry.url ? ` target="_blank" rel="noopener noreferrer"` : ""}>
              <span class="index-concept-number">${String(entry.number).padStart(3, "0")}</span>
              <span>${entry.name}</span>
              <span class="index-link-arrow" aria-hidden="true">↘</span>
            </a>
          </li>`).join("")}
      </ol>
    </section>`).join("");
}

const conceptSearch = document.querySelector("#concept-search");
if (conceptSearch && indexRoot) {
  const resultSummary = document.querySelector("#concept-search-summary");
  const emptyMessage = document.querySelector("#index-empty");

  const filterConcepts = () => {
    const query = normalizeText(conceptSearch.value.trim());
    let visibleTotal = 0;

    indexRoot.querySelectorAll(".index-card").forEach((card) => {
      let visibleInBlock = 0;
      card.querySelectorAll(".index-list li").forEach((item) => {
        const matches = item.dataset.conceptName.includes(query);
        item.hidden = !matches;
        if (matches) visibleInBlock += 1;
      });
      card.hidden = visibleInBlock === 0 && query.length > 0;
      const blockCount = card.querySelector("[data-index-total]");
      blockCount.textContent = query ? visibleInBlock : blockCount.dataset.total;
      visibleTotal += visibleInBlock;
    });

    resultSummary.textContent = query
      ? `${visibleTotal} ${visibleTotal === 1 ? "concepto encontrado" : "conceptos encontrados"}`
      : "128 conceptos en el índice";
    emptyMessage.hidden = visibleTotal !== 0;
  };

  conceptSearch.addEventListener("input", filterConcepts);
  document.addEventListener("keydown", (event) => {
    if ((event.ctrlKey || event.metaKey) && event.key.toLowerCase() === "k") {
      event.preventDefault();
      conceptSearch.focus();
    }
    if (event.key === "Escape" && document.activeElement === conceptSearch) {
      conceptSearch.value = "";
      filterConcepts();
    }
  });
}

const blockConceptRoot = document.querySelector("#block-concepts");
if (blockConceptRoot) {
  const blockNumber = Number(blockConceptRoot.dataset.blockNumber || 1);
  const block = conceptBlocks.find((item) => item.number === blockNumber);

  blockConceptRoot.innerHTML = block.topics.map((topic, topicIndex) => {
    const subtopics = topic.subtopics.map((subtopic, subtopicIndex) => {
      const entries = block.entries.filter((entry) => entry.subtopic === subtopic.title);
      const startNumber = entries[0]?.number ?? 1;
      const subtopicId = `tema-${topicIndex + 1}-${subtopicIndex + 1}`;

      return `
        <section class="detail-subtopic" aria-labelledby="${subtopicId}">
          <div class="detail-subtopic-heading">
            <h3 id="${subtopicId}">${subtopic.title}</h3>
            <span>${entries.length} CONCEPTOS</span>
          </div>
          <ol class="detail-concept-list" start="${startNumber}">
            ${entries.map((entry) => `
              <li>
                <a class="detail-concept-link" href="${entry.url || "#"}"${entry.url ? ` target="_blank" rel="noopener noreferrer"` : ""}>
                  <span class="detail-concept-number">${String(entry.number).padStart(3, "0")}</span>
                  <span class="detail-concept-name">${entry.name}</span>
                  <span class="detail-concept-arrow" aria-hidden="true">↗</span>
                </a>
              </li>`).join("")}
          </ol>
        </section>`;
    }).join("");

    return `
      <section class="detail-topic" aria-labelledby="detail-topic-${topicIndex + 1}">
        <div class="detail-topic-heading">
          <span class="detail-topic-number">0${topicIndex + 1}</span>
          <h2 id="detail-topic-${topicIndex + 1}">${topic.title}</h2>
        </div>
        <div class="detail-subtopic-grid">${subtopics}</div>
      </section>`;
  }).join("");
}

if ("IntersectionObserver" in window) {
  const revealElements = document.querySelectorAll(".index-card, .block-card, .detail-topic, .detail-subtopic");
  const revealObserver = new IntersectionObserver((entries, observer) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("is-visible");
        entry.target.addEventListener("transitionend", () => {
          entry.target.classList.remove("reveal-pending", "is-visible");
        }, { once: true });
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.12, rootMargin: "0px 0px -24px 0px" });

  revealElements.forEach((element, index) => {
    element.classList.add("reveal-pending");
    element.style.setProperty("--reveal-delay", `${(index % 3) * 75}ms`);
    revealObserver.observe(element);
  });
}
